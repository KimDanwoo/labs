import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parseBandSignals } from '../src/entities/track/lib/signals.ts';
import { TRACKS } from '../src/entities/track/model/constants/tracks.ts';

const directory = new URL('../public/signals/', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('index.json', directory), 'utf8'));
if (!Array.isArray(manifest) || !manifest.every((id) => Number.isSafeInteger(id) && id > 0))
  throw new Error('잘못된 분석 신호 목록');
const missing = [];
const invalid = [];
const highlights = {};
const available = TRACKS.filter((track) => track.isAvailable !== false);
for (const track of available) {
  const path = new URL(`${track.id}.json`, directory);
  if (!manifest.includes(track.id) || !existsSync(path)) {
    missing.push(track);
    continue;
  }
  let data;
  try {
    data = parseBandSignals(JSON.parse(readFileSync(path, 'utf8')));
  } catch {
    data = null;
  }
  if (!data || Math.abs(data.audioMs - track.durationMs) > 250) {
    invalid.push(track);
    continue;
  }
  const mid = Buffer.from(data.mid, 'base64');
  if (Math.abs((mid.length / data.fps) * 1000 - data.audioMs) > 1000) {
    invalid.push(track);
    continue;
  }
  const window = Math.min(mid.length, Math.round(data.fps * 15));
  let sum = 0;
  let best = -1;
  let start = 0;
  for (let index = 0; index < mid.length; index++) {
    sum += mid[index];
    if (index >= window) sum -= mid[index - window];
    if (index >= window - 1 && sum > best) {
      best = sum;
      start = index - window + 1;
    }
  }
  highlights[track.id] = Math.round(start / data.fps) * 1000;
}
const covered = available.length - missing.length - invalid.length;
process.stdout.write(
  `분석 신호 ${covered}/${available.length}곡 · 누락 ${missing.length}곡 · 오류 ${invalid.length}곡\n`,
);
for (const track of missing) process.stdout.write(`누락: ${track.title}\n`);
for (const track of invalid) process.stderr.write(`오류: ${track.title}\n`);
if (process.argv.includes('--write')) {
  const output = new URL('../src/entities/track/model/constants/highlights.ts', import.meta.url);
  writeFileSync(
    output,
    `// AUTO-GENERATED by scripts/check-signals.mjs --write\n// 원본 중역 에너지의 15초 이동평균이 가장 높은 구간.\nexport const HIGHLIGHTS: Readonly<Record<number, number>> = {\n${Object.entries(
      highlights,
    )
      .map(([id, ms]) => `  ${id}: ${ms},`)
      .join('\n')}\n};\n`,
  );
  process.stdout.write(`감상 구간 ${Object.keys(highlights).length}개 생성: ${fileURLToPath(output)}\n`);
}
if (invalid.length || (process.argv.includes('--strict') && missing.length)) process.exitCode = 1;
