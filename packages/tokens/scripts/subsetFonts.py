"""마루부리 원본(fonts/source)을 unicode-range 조각으로 나누고 fonts/maruburi.css를 생성한다.

실행: python3 packages/tokens/scripts/subsetFonts.py  (fonttools, brotli 필요 — 원본 교체 시에만)

같은 패밀리에서 unicode-range가 겹치면 나중에 선언한 face부터 확인하고, 글리프가 없으면 다음 face로 넘어간다
(CSS Fonts 4 font matching). 그래서 한글 두 조각은 같은 범위로 선언하되 상용 조각을 뒤에 두면,
보통 페이지는 latin + ko-common만 받고 KS X 1001 밖 글자('똠' 등)가 있을 때만 ko-rest를 받는다.
범위를 글자 단위로 나열하지 않아 CSS가 작다.
"""

from collections.abc import Callable
from pathlib import Path
from typing import NamedTuple

from fontTools import subset
from fontTools.ttLib import TTFont

FONTS_DIR = Path(__file__).resolve().parent.parent / "fonts"
SOURCE_DIR = FONTS_DIR / "source"
FAMILY = "MaruBuri"
# 조각을 받기 전·글리프가 없을 때 쓰는 대체 서체. 마루부리와 같은 명조 계열로 맞춘다.
FALLBACK_STACK = "'AppleMyungjo', 'Noto Serif KR', ui-serif, Georgia, serif"
WEIGHTS = {"Regular": 400, "SemiBold": 600, "Bold": 700}


def in_ranges(*ranges: tuple[int, int]) -> Callable[[int], bool]:
    return lambda codepoint: any(start <= codepoint <= end for start, end in ranges)


is_hangul = in_ranges((0xAC00, 0xD7A3))
is_compat_jamo = in_ranges((0x3130, 0x318F))
is_latin_core = in_ranges((0x0000, 0x00FF), (0x2000, 0x206F), (0x20A9, 0x20A9), (0x3000, 0x303F))


def is_common_hangul(codepoint: int) -> bool:
    # KS X 1001(EUC-KR)로 인코딩되는 2,350자가 실사용 한글의 대부분을 덮는다
    return is_hangul(codepoint) and len(chr(codepoint).encode("euc_kr", "ignore")) == 2


def is_symbol(codepoint: int) -> bool:
    # 확장 라틴·그리스 문자·기호처럼 드물게 쓰는 글자를 모은다
    return not (is_hangul(codepoint) or is_compat_jamo(codepoint) or is_latin_core(codepoint))


class Slice(NamedTuple):
    name: str
    unicode_range: str
    contains: Callable[[int], bool]


# 선언 순서 = 우선순위의 역순. 가장 자주 쓰는 조각을 맨 뒤에 둔다.
SLICES = (
    Slice("symbols", "U+0100-2FFF, U+3190-33FF, U+FB00-FFFF, U+1F100-1F1FF", is_symbol),
    Slice("ko-rest", "U+AC00-D7A3", lambda c: is_hangul(c) and not is_common_hangul(c)),
    Slice("ko-common", "U+3130-318F, U+AC00-D7A3", lambda c: is_common_hangul(c) or is_compat_jamo(c)),
    Slice("latin", "U+0000-00FF, U+2000-206F, U+20A9, U+3000-303F", is_latin_core),
)


def assert_slices_cover(codepoints: list[int]) -> None:
    covered = [c for c in codepoints if any(slice_.contains(c) for slice_ in SLICES)]
    assert covered == codepoints, f"조각에서 빠진 글자 {len(codepoints) - len(covered)}개"


def write_slice(source: Path, codepoints: list[int], target: Path) -> None:
    options = subset.Options()
    options.flavor = "woff2"
    # CFF 서브루틴을 풀면 woff2(brotli) 압축이 더 잘 먹어 조각 크기가 약 15% 줄어든다
    options.desubroutinize = True
    font = TTFont(source)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    font.flavor = "woff2"
    font.save(target)


def font_face(file_name: str, weight: int, unicode_range: str) -> str:
    return (
        "@font-face {\n"
        f"  font-family: '{FAMILY}';\n"
        f"  src: url('./{file_name}') format('woff2');\n"
        f"  font-weight: {weight};\n"
        "  font-style: normal;\n"
        "  font-display: swap;\n"
        f"  unicode-range: {unicode_range};\n"
        "}\n"
    )


def main() -> None:
    faces: list[str] = []
    for style, weight in WEIGHTS.items():
        source = SOURCE_DIR / f"{FAMILY}-{style}.woff2"
        codepoints = sorted(TTFont(source).getBestCmap())
        assert_slices_cover(codepoints)
        for slice_ in SLICES:
            file_name = f"{FAMILY}-{style}.{slice_.name}.woff2"
            write_slice(source, [c for c in codepoints if slice_.contains(c)], FONTS_DIR / file_name)
            faces.append(font_face(file_name, weight, slice_.unicode_range))

    header = "/* AUTO-GENERATED by scripts/subsetFonts.py — 직접 수정 금지 */\n\n"
    stack = f":root {{\n  --font-maruburi: '{FAMILY}', {FALLBACK_STACK};\n}}\n\n"
    (FONTS_DIR / "maruburi.css").write_text(header + stack + "\n".join(faces), encoding="utf-8")


if __name__ == "__main__":
    main()
